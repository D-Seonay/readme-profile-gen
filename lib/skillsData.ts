/** Recherche tolérante : nom, slug, alias ou catégorie. */
export const searchSkills = (query: string, list: readonly Skill[] = skillsData): Skill[] => {
  const q = query.trim().toLowerCase();
  if (!q) return [...list];
  return list.filter((s) =>
    s.name.toLowerCase().includes(q)
    || s.slug.includes(q)
    || s.category.includes(q)
    || (s.aliases ?? []).some((a) => a.toLowerCase().includes(q)));
};
